func writeOptions(p *page) error {
	p.macro("SH", "OPTIONS")
	p.text("Options can come before or after the game or scene.")
	var missing []string
	for _, f := range cli.Flags() {
		detail, ok := optionDetails[f.Long]
		if f.Long == "theme" {
			detail, ok = themeDetail(), true
		}
		if !ok {
			missing = append(missing, f.Long)
			continue
		}
		p.macro("TP")
		short, long := "`-"+f.Short+"`", "`--"+f.Long+"`"
		if f.Arg != "" {
			short, long = short+" <"+f.Arg+">", long+" <"+f.Arg+">"
		}
		p.line(p.phrase(short + ", " + long))
		p.text(detail)
		if f.Env != "" {
			p.text("The environment variable `" + f.Env + "` sets it too; the option wins.")
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("no description for option --%s in internal/tools/manpage", strings.Join(missing, ", --"))
	}
	return nil
}

func themeDetail() string {
	return fmt.Sprintf("Use the colour theme <name>: %s. The default is `%s`. The `norad` theme also shows the front panel.",
		joinAnd(bold(theme.Names()), "or"), theme.Default)
}

// bold marks up each of words in bold, for page.text.
func bold(words []string) []string {
	out := make([]string, len(words))
	for i, w := range words {
		out[i] = "`" + w + "`"
	}
	return out
}

// shellWords quotes each name that holds a space, as a shell needs it typed (wopr "noughts and
// crosses"), so that a list of names reads as the names it holds.
func shellWords(names []string) []string {
	out := make([]string, len(names))
	for i, n := range names {
		if strings.ContainsAny(n, " \t") {
			n = `"` + n + `"`
		}
		out[i] = n
	}
	return out
}

// joinAnd lists words in English: "a, b and c".
func joinAnd(words []string, and string) string {
	switch len(words) {
	case 0:
		return ""
	case 1:
		return words[0]
	}
	return strings.Join(words[:len(words)-1], ", ") + " " + and + " " + words[len(words)-1]
}

func writeGames(p *page, gs []game) {
	p.macro("SH", "GAMES")
	for _, g := range gs {
		title := g.Name
		if g.Number != nil {
			title = fmt.Sprintf("%d. %s", *g.Number, g.Name)
		}
		p.macro("SS", title)
		p.text("Start it with")
		p.macro("BR", g.Launch, ".")
		p.text("It also answers to " + joinAnd(bold(shellWords(g.Aliases)), "and") + ".")
		p.macro("PP")
		p.plain(g.Summary)
		p.macro("PP")
		p.text("How to play:")
		p.bullets(g.HowToPlay)
		p.macro("PP")
		p.text("Tips:")
		p.bullets(g.Tips[:manTips])
	}
}

func writeScenes(p *page) {
	p.macro("SH", "MOVIE SCENES")
	p.text("`wopr --movie` replays the film's scenes at WOPR's terminal, typed and paced as on screen, through the same console and games you play with. " +
		"These are the scenes, in the film's order:")
	for _, s := range movie.Scenes() {
		p.macro("TP")
		p.macro("B", fmt.Sprintf("%d %s", s.Number, s.Slug))
		p.plain(s.Blurb)
	}
	p.macro("PP")
	p.text("`wopr -m 3`, or `wopr -m first-strike`, or any start of a name that fits one scene, plays from that scene to the end, then exits. " +
		"With no scene, `wopr -m` opens a menu of the scenes. " +
		"Add `-o` (`--only`) to play just one scene. " +
		"`wopr --scenes` lists the scenes.")
	p.macro("PP")
	p.text("While a scene plays, Space pauses and resumes, `n` or Right skips to the next scene, `p` or Left goes back one, and Esc opens the menu. " +
		"Once the climax reaches tic-tac-toe, it plays to the end. " +
		"Every replay is the same: movie mode ignores `--seed` and `WOPR_SEED`.")
}

func writeEnd(p *page) {
	p.macro("SH", "EXIT STATUS")
	for _, s := range [][2]string{
		{"0", "The session ended normally: `LOGOFF`, the end of movie mode, a print-and-exit option, or SIGTERM."},
		{"1", "A runtime error or a crash."},
		{"2", "A usage error, such as an unknown option, game, scene or theme, a seed that is not a whole number, too many arguments, " +
			"options that cannot be combined, a name that fits more than one, or no terminal to run in (standard output is not a terminal, or `TERM` is `dumb`)."},
		{"130", "Ctrl+C or SIGINT."},
	} {
		p.macro("TP")
		p.macro("B", s[0])
		p.text(s[1])
	}

	p.macro("SH", "ENVIRONMENT")
	p.text("A variable that switches something on is false when it is empty or 0, false, no or off, and true otherwise.")
	for _, f := range cli.Flags() {
		if f.Env == "" {
			continue
		}
		p.macro("TP")
		p.macro("B", f.Env)
		if f.Arg == "" {
			p.text("When true, it turns on `--" + f.Long + "` (" + f.Help + ").")
		} else {
			p.text("It gives `--" + f.Long + "` its value (" + f.Help + "). Empty is the same as unset.")
		}
	}
	for _, e := range [][2]string{
		{"WOPR_PANEL", "Shows the front panel when true and hides it when false, in any theme. Unset or empty, the theme decides: `norad` shows it."},
		{"WOPR_DEBUG", "When true, `wopr` writes a debug log (never what you type) and prints its path when it exits. See FILES."},
		{"NO_COLOR", "Set to any non-empty value, it turns colour off."},
		{"TERM", "When it is `dumb`, `wopr` does not start its full-screen interface and exits with status 2; the options that print and exit still work."},
	} {
		p.macro("TP")
		p.macro("B", e[0])
		p.text(e[1])
	}

	p.macro("SH", "FILES")
	p.macro("TP")
	p.macro("I", "~/.cache/wopr/debug.log")
	p.text("The debug log that `WOPR_DEBUG` turns on. It is under <$XDG_CACHE_HOME> when that is set, and in <~/Library/Caches/wopr> on macOS.")

	p.macro("SH", "NOTES")
	p.text("`wopr` is a fan-made homage. It is not affiliated with or endorsed by the makers or owners of <WarGames>. " +
		"The code is under the MIT licence. Film quotations and third-party text are not covered by it; " +
		"`wopr --licenses` prints the licence, <NOTICE.md>, which says what they are and who they belong to, " +
		"and the licences of the third-party code built into `wopr`.")

	p.macro("SH", "BUGS")
	// The URL ends its line, with no full stop that a terminal could take as part of it.
	p.text("Report bugs in the issue tracker: " + issuesURL)
	p.macro("PP")
	p.text("Run `wopr` with `WOPR_DEBUG=1` and attach the debug log it names when it exits, with the seed if you used one. " +
		"The full-screen interface has not yet been tried with a screen reader.")

	p.macro("SH", "EXAMPLES")
	for _, ex := range [][2]string{
		{"wopr", "Dial in and log on."},
		{"wopr chess -i", "Play chess with no typewriter pacing."},
		{"wopr --games", "List the games."},
		{"wopr -m 2", "Replay the film from scene 2."},
		{"wopr -m joshua -o", "Replay just the `joshua` scene."},
		{"WOPR_THEME=green wopr -r", "Use the `green` theme, with no blinking."},
	} {
		p.macro("TP")
		p.macro("B", ex[0])
		p.text(ex[1])
	}

	p.macro("SH", "SEE ALSO")
	p.text("The guide to `wopr` and its games, with screenshots: " + siteURL)
	p.line(".br")
	p.text("The source code: " + repoURL)
}

