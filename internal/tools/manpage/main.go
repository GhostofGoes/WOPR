// like other names they are never split (see page.literal). A man(7) link, the .UR macro,
// would not help: with hyperlinks off, groff 1.23 prints the URL in angle brackets that are
// not ASCII, and mandoc's lint warns of an empty block.
const (
	siteURL   = cli.DocsURL
	repoURL   = "https://github.com/GhostofGoes/WOPR"
	issuesURL = repoURL + "/issues"
)
